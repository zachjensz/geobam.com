#!/usr/bin/env node
/**
 * Slims the world-countries dataset (https://github.com/mledoze/countries)
 * down to the fields geobam.com actually reads.
 *
 * The full dataset ships every ISO 3166-1 entry with ~19 top-level fields
 * (~1.4 MB raw); the quiz only reads name, aliases, codes, location, size,
 * region, borders, capital and UN membership. Keeping only those fields cuts
 * the bundled data by a large margin.
 *
 * Output: src/data/countries-slim.json
 *   - a JSON array of trimmed entries, preserving the original order exactly,
 *   - prefixed with a comment header carrying the ODbL attribution.
 *
 * world-countries is licensed under the Open Database License (ODbL) v1.0:
 * https://opendatacommons.org/licenses/odbl/1.0/
 *
 * Usage: npm run data:slim
 */
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)

const countriesPath = require.resolve('world-countries/countries.json')
const countries = JSON.parse(readFileSync(countriesPath, 'utf8'))

const packagePath = require.resolve('world-countries/package.json')
const { version } = JSON.parse(readFileSync(packagePath, 'utf8'))

/**
 * The exact fields read by src/games/countries/curriculum.ts,
 * src/games/capitals/curriculum.ts and src/games/countries/detailedGeometry.ts.
 * Nothing else from a country entry is used anywhere in src/.
 */
function slim(country) {
  return {
    name: {
      common: country.name.common,
      official: country.name.official,
    },
    altSpellings: country.altSpellings,
    cca3: country.cca3,
    ccn3: country.ccn3,
    latlng: country.latlng,
    area: country.area,
    region: country.region,
    subregion: country.subregion,
    borders: country.borders,
    capital: country.capital,
    unMember: country.unMember,
  }
}

// Array order is preserved exactly so curriculum ordering stays byte-for-byte
// identical to the full dataset.
const slimmed = countries.map(slim)

const header = [
  '// Trimmed copy of the world-countries dataset, generated by scripts/slim-countries.mjs — do not edit by hand.',
  '//',
  `// Derived from world-countries v${version} (https://github.com/mledoze/countries)`,
  '// by Mohammed Le Doze and contributors.',
  '// Licensed under the Open Database License (ODbL) v1.0:',
  '// https://opendatacommons.org/licenses/odbl/1.0/',
  '//',
  '// Only the fields used by geobam.com are retained; the original order is preserved.',
  '//',
].join('\n')

const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'countries-slim.json')
mkdirSync(dirname(outPath), { recursive: true })

const payload = JSON.stringify(slimmed)
writeFileSync(outPath, `${header}\n${payload}\n`)

console.log(
  `Wrote ${outPath}: ${slimmed.length} countries, ` +
  `${(Buffer.byteLength(payload) / 1024).toFixed(1)} kB of data (down from ` +
  `${(Buffer.byteLength(JSON.stringify(countries)) / 1024).toFixed(1)} kB).`,
)
